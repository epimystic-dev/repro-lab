"""Emit a .py script from a parsed notebook.

Two modes:

  - ``linear`` - cells in file order, which is what the notebook would
    be if executed with 'Restart and Run All'. This is the mode a
    reviewer wants when they ask "what does the author claim this
    notebook does."
  - ``executed`` - cells in order of recorded execution_count, which
    reflects what the kernel actually saw during the author's session.
    This is the mode a reviewer wants when they ask "what did the
    kernel see at the time the recorded outputs were produced." Cells
    with execution_count=null are placed after executed cells, in file
    order, with a comment banner.
"""

from __future__ import annotations

from typing import List

from .notebook import CodeCell, Notebook


_BANNER_LINEAR = (
    "# Generated by nbexport in LINEAR mode: cells in file order.\n"
    "# A clean nbexport run means the record is internally consistent;\n"
    "# it does not guarantee this script will run top-to-bottom.\n"
)

_BANNER_EXECUTED = (
    "# Generated by nbexport in EXECUTED mode: cells ordered by\n"
    "# recorded execution_count. Never-run cells follow at the end.\n"
    "# A clean nbexport run means the record is internally consistent;\n"
    "# it does not guarantee this script will run top-to-bottom.\n"
)


def _cell_banner(c: CodeCell) -> str:
    ec = c.execution_count
    tag = "ec=" + str(ec) if ec is not None else "ec=null"
    return "\n# --- cell[" + str(c.index) + "] " + tag + " ---\n"


def _render(cells: List[CodeCell]) -> str:
    parts: List[str] = []
    for c in cells:
        parts.append(_cell_banner(c))
        src = c.source
        # Strip line magics, shell commands and IPython help operators
        # from the emitted script so plain python runs cleanly; keep
        # them as comments so the reader can see what was there.
        out_lines = []
        for line in src.splitlines():
            stripped = line.lstrip()
            if (stripped.startswith("%") or stripped.startswith("!")
                    or stripped.startswith("?")):
                out_lines.append("# nbexport: " + line)
            else:
                out_lines.append(line)
        parts.append("\n".join(out_lines))
        if not src.endswith("\n"):
            parts.append("\n")
    return "".join(parts)


def emit_script(nb: Notebook, mode: str) -> str:
    cells = list(nb.code_cells)
    if mode == "executed":
        executed = sorted(
            [c for c in cells if c.execution_count is not None],
            key=lambda c: c.execution_count or 0,
        )
        never_run = [c for c in cells if c.execution_count is None]
        return _BANNER_EXECUTED + _render(executed + never_run)
    # Default: linear.
    return _BANNER_LINEAR + _render(cells)


__all__ = ["emit_script"]
